// Movie caption tables.  movie_title_dat.o carries no code -- these tables are
// the whole translation unit (.data 336ec8, 0x1538 bytes; .rodata 3c1a38).
//
// One movie_NNNN[] per cutscene that has captions: a list of
// { message id, first frame, last frame + 1 }, terminated by { -1, -1, -1 }.
// The frame numbers are NTSC; GetMovieTitleDatTblPos() scales them by 5/6 in
// PAL.  movie_title_dat[] then indexes those lists by scene number.
//
// Twenty of the 71 scenes have no captions and share movie_001[], a list that
// is nothing but the terminator.  Four tables -- movie_0131, movie_0201,
// movie_0620 and movie_1041 -- are in .data but nothing points at them; they
// survive because they are file-scope globals rather than statics, which is
// also why every table here is non-static.  Their scene numbers all resolve to
// movie_001[], so those four cutscenes ship with their captions authored and
// unreachable.
//
// Extracted verbatim from the Feb 6 2004 prototype (SLES_523.84).

