// Persistent per-object map state.
//
// A room's MDAT_OBJ records live in the registration buffer and are thrown
// away when the room unloads, so anything an event did to an object -- opened
// it, made it invisible, marked it photographed -- has to be parked somewhere
// that outlives the room.  That somewhere is MapSaveList: one flat, ordered
// entry per save-able object in the game, built at compile time and written
// to the memory card verbatim.
//
// The flow is symmetric.  On room load MapSaveSetMstDat() pushes the saved
// state down into the fresh MDAT_OBJ records; every frame afterwards
// MapObjProc() pulls each live record back up through MapSaveCopyDat().
//
// Labels are <area>*1000 + <object>.  The table is grouped by area with the
// labels ascending inside each group, but the areas are in no useful order,
// so MapSaveRegist() builds a one-entry-per-area jump table and lookups do a
// linear walk from there.
//
// Reconstructed from the Feb 6 2004 prototype (SLES_523.84), MapSave.o
// 0x00111598..0x00111d2f.

