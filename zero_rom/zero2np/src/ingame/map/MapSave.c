/* One entry per distinct area, in table order.  Rebuilt by MapSaveRegist(). */
static MAPSAVE_JMP_TBL MapSaveJmp[MAPSAVE_MAX];                         /* bss 41ac60 */
static int             MapSaveJmpNum;                                   /* sbss 3f4a9c */

/* Pristine copy of MapSaveList taken at boot, before any event has run. */
static MAPSAVE_HEAD MapSaveFirstWork[MAPSAVE_MAX];                      /* bss 41c168 */

/* Finds one label's save block: pick the area's run out of the jump table,
 * then walk it.  Both failure modes are silent-ish by design -- an unknown
 * area just returns NULL, because events fire against objects in rooms that
 * are not in the table at all. */
static MAPSAVE_HEAD *MapSaveGetDatPtr(int label)                        /* 37 */
{
    int           i;
    MAPSAVE_HEAD *hp;

    for (i = 0; i < MapSaveJmpNum; i++)                                 /* 42 */
    {
        if (MapSaveJmp[i].AreaID == label / 1000)                       /* 43 */
        {
            break;
        }
    }                                                                   /* 45 */

    if (i == MapSaveJmpNum)                                             /* 48 */
    {
        return (MAPSAVE_HEAD *)0;                                       /* 49 */
    }
    hp = MapSaveJmp[i].head;                                            /* 51 */

    while (hp->labelID != label)                                        /* 53 */
    {
        if (hp >= &MapSaveList[MAPSAVE_MAX - 1])                        /* 56 */
        {
            return (MAPSAVE_HEAD *)0;
        }

        /* Walked past this area's run without a hit.  The map data names a
         * label the table does not carry, which means the two were built
         * from different revisions of the area. */
        if (hp->labelID / 1000 != label / 1000)                         /* 60 */
        {
            PRINT_ERROR("CHANGE_LABEL_ID[%d][%d]\n", hp->labelID, label);/* 61 */

            return (MAPSAVE_HEAD *)0;                                   /* 63 */
        }
        hp++;                                                           /* 65 */
    }
    return hp;                                                          /* 67 */
}                                                                       /* 68 */

void *MapSaveGetTblPtr(int label)                                       /* 72 */
{
    return MapSaveGetDatPtr(label);                                     /* 74 */
}

int MapSaveGetStat(int label, int stat)                                 /* 79 */
{
    MAPSAVE_HEAD *hp = MapSaveGetDatPtr(label);                         /* 81 */

    if (hp == (MAPSAVE_HEAD *)0) return -1;                             /* 82 */

    switch (stat)                                                       /* 84 */
    {
    case 0: return (int)hp->HitCheck;                                   /* 85 */
    case 1: return (int)hp->PhotoAble;                                  /* 86 */
    case 2: return (int)hp->Visible;                                    /* 87 */
    case 3: return (int)hp->ActionType;                                 /* 88 */
    case 4: return (int)hp->Action;                                     /* 89 */
    case 5: return (int)hp->Weight;                                     /* 90 */
    case 6: return hp->Attribute;                                       /* 91 */
    default:
        PRINT_ERROR("NO_SAVE_STAT[%d]\n", stat);                        /* 93 */
        return -1;                                                      /* 94 */
    }                                                                   /* 95 */
}

void MapSaveSetStat(int label, int stat, int num)                       /* 100 */
{
    MAPSAVE_HEAD *hp = MapSaveGetDatPtr(label);                         /* 102 */

    if (hp == (MAPSAVE_HEAD *)0) return;                                /* 103 */

    switch (stat)                                                       /* 105 */
    {
    case 0: hp->HitCheck   = (char)num;  break;                         /* 106 */
    case 1: hp->PhotoAble  = (char)num;  break;                         /* 107 */
    case 2: hp->Visible    = (char)num;  break;                         /* 108 */
    case 3: hp->ActionType = (char)num;  break;                         /* 109 */
    case 4: hp->Action     = (short)num; break;                         /* 110 */
    case 5: hp->Weight     = (short)num; break;                         /* 111 */
    case 6: hp->Attribute  = num;        break;                         /* 112 */
    default:
        PRINT_ERROR("NO_SAVE_STAT[%d]\n", stat);                        /* 113 */
    }                                                                   /* 115 */
}

/* Room-load half of the mirror: pushes the saved state of every object record
 * in one registration file back down into the freshly loaded MDAT_OBJs, before
 * MapObjRegistRegDatOne() turns them into draw entries.
 *
 * The ROM keeps the walk cursor typed as the record header and casts at each
 * field, which is why `stp` is an MB_OUT_SECTION* rather than an MDAT_OBJ*
 * -- type 3 guarantees the record really is an MDAT_OBJ. */
void MapSaveSetMstDat(int reg_id)                                       /* 119 */
{
    MB_OUT_SECTION *stp;
    MAPSAVE_HEAD   *hp;

    RegDatGetStPtrStart(reg_id, 3);                                     /* 123 */

    while ((stp = RegDatGetNextStPtr(reg_id)) != (MB_OUT_SECTION *)0)   /* 125 */
    {
        hp = MapSaveGetDatPtr((int)stp->labelID);                       /* 127 */

        if (hp == (MAPSAVE_HEAD *)0)                                    /* 130 */
        {
            PRINT_ERROR("NO_SAVE_DAT[%s]label[%d]\n",                   /* 131 */
                        ((MDAT_OBJ *)stp)->ModelName, stp->labelID);    /* 132 */
            continue;                                                   /* 133 */
        }

        ((MDAT_OBJ *)stp)->HitCheck   = hp->HitCheck;                   /* 140 */
        ((MDAT_OBJ *)stp)->PhotoAble  = hp->PhotoAble;                  /* 141 */
        ((MDAT_OBJ *)stp)->Visible    = hp->Visible;                    /* 142 */
        ((MDAT_OBJ *)stp)->ActionType = hp->ActionType;                 /* 143 */
        ((MDAT_OBJ *)stp)->Action     = hp->Action;                     /* 144 */
        ((MDAT_OBJ *)stp)->Weight     = hp->Weight;                     /* 145 */
        ((MDAT_OBJ *)stp)->Attribute  = hp->Attribute;                  /* 146 */
    }
}

/* Per-frame half of the mirror: pulls one live MDAT_OBJ's mutable state back
 * up into its save block.  `out` is the MAPSAVE_HEAD and `mst` the MDAT_OBJ;
 * both arrive as void* because MAPOBJ_DAT stores them untyped. */
void MapSaveCopyDat(void *out, void *mst)                               /* 156 */
{
    MDAT_OBJ *op = (MDAT_OBJ *)mst;                                     /* 157 */

    if (mst == (void *)0 || out == (void *)0)                           /* 160 */
    {
        /* The message names the two pointers the other way round from the
         * parameters.  Kept as found. */
        PRINT_ERROR("NO_POINTER: op[%x] hp[%x]\n",                      /* 161 */
                    (u_int)(uintptr_t)mst, (u_int)(uintptr_t)out);
        return;
    }

    ((MAPSAVE_HEAD *)out)->HitCheck  = (char)op->HitCheck;              /* 165 */
    ((MAPSAVE_HEAD *)out)->PhotoAble = (char)op->PhotoAble;             /* 166 */
    ((MAPSAVE_HEAD *)out)->Visible   = (char)op->Visible;               /* 167 */
    ((MAPSAVE_HEAD *)out)->Action    = (short)op->Action;               /* 168 */
    ((MAPSAVE_HEAD *)out)->Weight    = (short)op->Weight;               /* 169 */
    ((MAPSAVE_HEAD *)out)->Attribute = op->Attribute;                   /* 170 */

    /* ActionType is stored inverted for the two door-ish actions holding a
     * negative type, and for every model whose name's second character is
     * '9'.  ~(-1) is 0, so a "no type yet" record saves as 0 and a resolved
     * one saves as its complement -- that is what tells the two apart on
     * reload, since the field is otherwise indistinguishable from unset. */
    if (((op->Action == 4 || op->Action == 5) && op->ActionType < 0)    /* 174 */
        || op->ModelName[1] == '9')
    {
        ((MAPSAVE_HEAD *)out)->ActionType = (char)~op->ActionType;      /* 178 */
    }
    else
    {
        ((MAPSAVE_HEAD *)out)->ActionType = (char)op->ActionType;       /* 180 */
    }
}

/* Rebuilds the per-area jump table by scanning for the boundaries between
 * runs.  Cheap enough to just rerun after any bulk write to MapSaveList. */
void MapSaveRegist(void)                                                /* 188 */
{
    int i;                                                              /* 189 */
    int id = -1;                                                        /* 190 */

    MapSaveJmpNum = 0;                                                  /* 192 */
    for (i = 0; i < MAPSAVE_MAX; i++)                                   /* 193 */
    {
        if (MapSaveList[i].labelID / 1000 != id)                        /* 194 */
        {
            id = MapSaveList[i].labelID / 1000;                         /* 195 */
            MapSaveJmp[MapSaveJmpNum].AreaID = id;                      /* 196 */
            MapSaveJmp[MapSaveJmpNum].head   = &MapSaveList[i];         /* 197 */
            MapSaveJmpNum++;                                            /* 198 */
        }
    }                                                                   /* 200 */
}

void MapSaveCallback(MC_SAVE_DATA *data)                                /* 207 */
{
    data->addr = (u_char *)MapSaveList;                                 /* 208 */
    data->size = sizeof(MapSaveList);                                   /* 209 */
}

void MapSavePushFirstDat(void)                                          /* 216 */
{
    memcpy(MapSaveFirstWork, MapSaveList, sizeof(MapSaveList));         /* 218 */
}

void MapSavePopFirstDat(void)                                           /* 223 */
{
    memcpy(MapSaveList, MapSaveFirstWork, sizeof(MapSaveList));         /* 225 */
}
