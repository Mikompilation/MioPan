/* The registry entry for a door id, matched on slot 0's record. */
static MAPDOOR_HEAD *MapDoorCheckID(int door_id)
{                                                                       /* 176 */
    for (int i = 0; i < MAPDOOR_LIST_NUM; i++)                          /* 179 */
    {
        if (MapDoorList[i].buff_id[0] != -1 &&
            MapDoorList[i].dat[0] != (MDAT_DOOR *)0 &&
            MapDoorList[i].dat[0]->DatID == door_id)
        {
            return &MapDoorList[i];                                     /* 185 */
        }
    }

    return (MAPDOOR_HEAD *)0;                                           /* 186 */
}

/* Drops `buff_id` from every entry.
 *
 * Slot 1 is simply cleared.  Slot 0 is the live one, so when it is the buffer
 * going away the neighbour slides down into it and the put-object is handed to
 * that buffer -- this is what keeps a door drawn while the player is standing
 * in its frame with the old room already unloaded. */
void MapDoorDeleteBuff(int buff_id)
{                                                                       /* 190 */
    for (int i = 0; i < MAPDOOR_LIST_NUM; i++)                          /* 193 */
    {
        MAPDOOR_HEAD *hp = &MapDoorList[i];

        if (hp->buff_id[1] == buff_id)
        {
            hp->buff_id[1] = -1;
            hp->dat[1]     = (MDAT_DOOR *)0;
        }

        if (hp->buff_id[0] == buff_id)                                  /* 202 */
        {
            hp->buff_id[0] = hp->buff_id[1];
            hp->dat[0]     = hp->dat[1];
            hp->buff_id[1] = -1;
            hp->dat[1]     = (MDAT_DOOR *)0;

            if (hp->buff_id[0] != -1)
            {
                if (hp->hdl == (void *)0)
                {
                    PRINT_ERROR("NO_MAPPUT_HDL[%d]\n", hp->buff_id[0]); /* 205 */
                }
                else
                {
                    MapPutSetBuffID(hp->hdl, hp->buff_id[0]);
                }
            }
        }
    }
}                                                                       /* 209 */

/* First entry with a free slot 0, wiped ready for use. */
static MAPDOOR_HEAD *MapDoorGetFreeSpace(void)
{                                                                       /* 159 */
    for (int i = 0; i < MAPDOOR_LIST_NUM; i++)                          /* 162 */
    {
        if (MapDoorList[i].buff_id[0] == -1)
        {
            MapDoorList[i].buff_id[1] = -1;                             /* 167 */
            MapDoorList[i].dat[0]     = (MDAT_DOOR *)0;
            MapDoorList[i].dat[1]     = (MDAT_DOOR *)0;
            MapDoorList[i].hdl        = (void *)0;

            return &MapDoorList[i];                                     /* 169 */
        }
    }

    /* No newline in the ROM's string. */
    PRINT_ERROR("FREE_DOOR_CTL_SPACE");                                 /* 170 */

    return (MAPDOOR_HEAD *)0;
}

/* Registers `op` under `buff_id`.
 *
 * A door already claimed by the other buffer takes the second slot and returns
 * 0 -- the caller treats that as "nothing new to place", because the object is
 * already in the draw list from the first room's load.  The door the player is
 * currently walking through additionally has its collision dropped, so it does
 * not become solid again the instant the second room streams in. */
uintptr_t MapDoorAdd(int buff_id, MDAT_DOOR *op)
{                                                                       /* 219 */
    MAPDOOR_HEAD *hp = MapDoorCheckID(op->DatID);                       /* 221 */

    if (hp != (MAPDOOR_HEAD *)0)
    {
        printf("DOOR REGIST YET buff_id = %d op->DatID = %d \n",
               buff_id, op->DatID);                                     /* 225 */

        hp->buff_id[1] = buff_id;                                       /* 226 */
        hp->dat[1]     = op;

        if (op->DatID == MapDoorCtlID)
        {
            op->HitCheck = 0;
        }

        return 0;
    }

    /* Called twice in the original: once to test, once to claim. */
    if (MapDoorGetFreeSpace() == (MAPDOOR_HEAD *)0)
    {
        PRINT_ERROR("NO_SPACE_DOOR_BUFFER\n");                          /* 230 */
        return 0;                                                       /* 231 */
    }

    hp = MapDoorGetFreeSpace();
    hp->buff_id[0] = buff_id;                                           /* 239 */
    hp->dat[0]     = op;

    return (uintptr_t)hp;                                               /* 240 */
}

