// Map door controller: the doors that are currently resident, and the
// open/close transition the player walks through.
//
// Two things live here.  The first is a 16-entry registry.  A door record is
// registered by MapObjRegistDoor() as part of an ordinary room load, but a
// doorway belongs to *two* rooms, so each entry holds a pair: slot 0 is the
// buffer that registered it first and slot 1 the neighbour that found the same
// DatID already present.  MapDoorDeleteBuff() is what makes that work -- when
// the first room is torn down the second slot slides into the first and the
// put-object is re-pointed at the surviving buffer, so the door keeps drawing
// across the transition.
//
// The second is the transition itself: MapDoorSetAnimID() latches the door the
// player is entering, MapDoorAnimOpen() starts the motion and the sound, and
// MapDoorAnimClose() puts everything back and places the sister on the far
// side.  Between those two the door is drawn by MapDoorPutCallback() rather
// than the ordinary object path, because it has to be pre-lit against both
// rooms at once.
//
// Reconstructed from the Feb 6 2004 prototype (SLES_523.84), MapDoor.o
// 0x001052e0..0x00107277.

