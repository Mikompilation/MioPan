/* Turns a door's authored yaw into the player's (or sister's) facing.
 *
 * The four dead zones pick whether the door's own rotation adds to or subtracts
 * from the record's stored angle, i.e. which way round the frame the actor
 * comes out.  All four call sites use it identically. */
static float MapDoorCalcRotY(float base, float rot_y)
{                                                                       /* 355 */
    float r;

    if (rot_y < -3.0f && rot_y > -86.0f)                                /* 357 */
    {
        r = base - rot_y;
    }
    else if (rot_y >= 176.0f)                                           /* 362 */
    {
        r = base + rot_y;
    }
    else if (rot_y > 93.0f)                                             /* 363 */
    {
        r = base - rot_y;
    }
    else
    {
        r = base + rot_y;
    }

    return r * MAPDOOR_DEG2RAD;                                         /* 367 */
}

