/* Latches the door the player has just triggered: collision off, player placed
 * at the approach mark, light set up and the model and sound bank requested.
 * The actual motion does not start until MapDoorAnimOpen(). */
void MapDoorSetAnimID(int door_type)
{                                                                       /* 637 */
    MLOAD_DOOR_DAT *hp = MapDoorGetDatListPtr(door_type);               /* 638 */
    MAPDOOR_HEAD   *dp;
    MLOAD_HEAD     *lp;

    if (hp == (MLOAD_DOOR_DAT *)nullptr)
    {
        return;
    }

    MapDoorCtlID      = hp->doorID;                                     /* 640 */
    plyr_wrk.door_no  = (u_short)door_type;                             /* 641 */
    MapDoorAnimType   = door_type;                                      /* 643 */
    MapDoorRoomNo     = GetPlyrAreaNo();                                /* 645 */

    printf("door_type[%d] room_no[%d]***************\n", door_type, MapDoorRoomNo);  /* 648 */

    if (MapDoorSetHitFlg(MapDoorCtlID, 0) < 0)                          /* 649 */
    {
        PRINT_ERROR("CANNOT_CHANGE_HIT_FLG[%d]\n", MapDoorCtlID);       /* 653 */
    }

    SetPlayerHitRadius(MAPDOOR_HIT_RADIUS);                             /* 655 */
    MapDoorAnimSetPos();                                                /* 657 */
    ReqPlyrDoorMotion((u_int)hp->type, 0);                              /* 659 */

    dp = MapDoorCheckID(MapDoorCtlID);                                  /* 661 */
    lp = MapLoadGetHeadPtr(MapLoadGetBuffID(MapDoorRoomNo));            /* 663 */

    if (MapMeiCheck(lp) == 0)                                           /* 666 */
    {
        MapLightSetScale(&MapDoorLight, MapDrawGetLightPtr(MapDoorRoomNo)); /* 668 */
        MapPutSetLitPtr(dp->hdl, &MapDoorLight);                        /* 670 */
        *(u_int *)MapPutGetFlgPtr(dp->hdl) |= MAPDOOR_PUT_FLG_PRELIT;
    }
    else
    {
        MapPutSetLitPtr(dp->hdl, MapMeiGetLight());                     /* 674 */
    }

    if (door_bank_id != -1)                                             /* 675 */
    {
        SndBankRelease(door_bank_id);
    }
    door_bank_id = SndBankNew((u_int)hp->se, hp->se - 1, -1);           /* 678 */

    MapDoorLoadReq(dp->dat[0]->ModelName);                              /* 680 */

    /* Two doors still need the plain single-room path while the monotone
     * (photo-negative) draw mode is on. */
    MapDoorSp = 0;                                                      /* 684 */
    if (gra3dIsMonotoneDrawEnable() != 0 &&                             /* 687 */
        (strncmp(dp->dat[0]->ModelName, MAPDOOR_SP_NAME_0, 4) == 0 ||
         strncmp(dp->dat[0]->ModelName, MAPDOOR_SP_NAME_1, 4) == 0))
    {
        MapDoorSp = 1;
    }
}                                                                       /* 690 */

