/* Starts the transition: swaps the door onto the dual-room light, hands it to
 * MapDoorPutCallback(), and kicks off the motion and the sound. */
int MapDoorAnimOpen(void)
{                                                                       /* 706 */
    MLOAD_DOOR_DAT *hp = MapDoorGetDatListPtr(MapDoorAnimType);         /* 713 */
    MAPDOOR_HEAD   *dp;
    int             type;
    float           vPos[4];

    if (hp == (MLOAD_DOOR_DAT *)nullptr)
    {
        return -1;
    }

    if ((u_short)hp->type < MAPDOOR_MOTION_NUM)                         /* 714 */
    {
        type = (int)(u_short)hp->type;
    }
    else
    {
        type = 0;                                                       /* 716 */
        PRINT_ERROR("NO_MOTION_USE_TES_MOTION\n");                      /* 717 */
    }

    dp = MapDoorCheckID(MapDoorCtlID);                                  /* 725 */
    printf("MapDoorRoomNo = %d\n", MapDoorRoomNo);                      /* 726 */

    if (MapMeiCheck(MapLoadGetHeadPtr(MapLoadGetBuffID(MapDoorRoomNo))) != 0) /* 729 */
    {
        G3DASSERT(dp, "");                                              /* 731 */
        MapPutSetLitPtr(dp->hdl, MapMeiGetLight());                     /* 734 */
    }
    else
    {
        G3DASSERT(dp, "");                                              /* 739 */

        _SetVector(vPos, dp->dat[0]->Pos[0], dp->dat[0]->Pos[1],
                   dp->dat[0]->Pos[2], 1.0f);                           /* 744 */

        /* Only blend when the two sides really are different rooms -- an
         * internal door joining a room to itself keeps its own light. */
        if (MapMeiCheck(MapLoadGetHeadPtr(MapLoadGetBuffID(MapDoorRoomNo) ^ 1)) == 0 &&
            hp->room_no[0] != hp->room_no[1])                           /* 746, 750 */
        {
            MapDoorMakeDualRoomLight(&MapDoorLight, vPos,
                                     MapPutGetModelPtr(dp->hdl));       /* 752 */
            MapPutSetLitPtr(dp->hdl, &MapDoorLight);                    /* 755 */
        }

        if (MapDoorLight.vAmbient[0] == 0.0f &&                         /* 759 */
            MapDoorLight.vAmbient[1] == 0.0f &&
            MapDoorLight.vAmbient[2] == 0.0f)
        {
            MapDoorLight.vAmbient[0] = MAPDOOR_AMBIENT_MIN;             /* 764 */
        }

        MapPutChangeFunc(dp->hdl, MapDoorPutCallback);                  /* 765 */
        iBuffSw = 0;
    }

    ReqPlyrDoorMotion((u_int)type, 1);                                  /* 770 */
    MapDoorAnim(type);                                                  /* 771 */
    SndBankPlay(door_bank_id, 0, 1, 1, 0x3200, 0x1000, 0,
                (SND_3D_SET *)0);                                       /* 772 */

    return 0;                                                           /* 774 */
}                                                                       /* 775 */

/* Ends the transition: drops the animation and its hit records, restores the
 * door's own matrix and light, and places the sister on whichever side she
 * belongs. */
int MapDoorAnimClose(int door_id)
{                                                                       /* 779 */
    MAPDOOR_HEAD   *hp;
    MLOAD_DOOR_DAT *dp;
    MLOAD_HEAD     *lp;
    MDAT_DOOR      *door;
    int             now_room_no;
    float           rpos[4];
    float           mat[4][4];
    float           vw[4];
    float           fw;

    if (MapDoorAnimID >= 0)                                             /* 785 */
    {
        if (MapDoorAnimID < MAPDOOR_MANIM_BASE)                         /* 787 */
        {
            MapAnimDelete(MapDoorAnimID);                               /* 788 */
        }
        else
        {
            MapManimUnitMatrix(MapDoorAnimID / MAPDOOR_MANIM_BASE - 1); /* 791 */
            MapManimDeleteOne(MapDoorAnimID / MAPDOOR_MANIM_BASE - 1);  /* 793 */
        }
        MapDoorAnimID = -1;                                             /* 797 */
    }

    MapHitDeleteDoorRec();                                              /* 800 */
    MapDoorSetHitFlg(MapDoorCtlID, 1);                                  /* 804 */

    hp = MapDoorCheckID(MapDoorCtlID);                                  /* 806 */
    if (hp == (MAPDOOR_HEAD *)0)
    {
        return -1;                                                      /* 807 */
    }

    door = hp->dat[0];

    if (hp->hdl != (void *)0)                                           /* 815 */
    {
        now_room_no = GetPlyrAreaNo();                                  /* 816 */

        /* Straight back into the put-object's own matrix -- the animation was
         * driving it, and it has to end up back at the authored placement. */
        MapDoorSetMatrix(*MapPutGetMatrixPtr(hp->hdl),
                         door->Pos, door->Rot);                         /* 817, 823 */

        lp = MapLoadGetHeadPtr(MapLoadGetBuffID(now_room_no));           /* 825 */
        if (MapMeiCheck(lp) == 0)                                       /* 827 */
        {
            MapPutSetLitPtr(hp->hdl, (GRA3DLIGHTDATA *)0);              /* 830 */
            *(u_int *)MapPutGetFlgPtr(hp->hdl) |= MAPDOOR_PUT_FLG_PRELIT;

            if (MapDoorRoomNo == now_room_no)                           /* 832 */
            {
                MapLightPreRenderObj2(hp->hdl, MapDoorRoomNo);          /* 838 */
            }
        }
        else
        {
            *(u_int *)MapPutGetFlgPtr(hp->hdl) &= ~(MAPDOOR_PUT_FLG_PRELIT | 0x800);
            MapPutSetLitPtr(hp->hdl, MapMeiGetLight());                 /* 840 */
        }

        MapPutChangeObj(hp->hdl);                                       /* 844 */
    }

    if (IsSisWrk() != 0)                                                /* 848 */
    {
        if (MapDoorRoomNo != GetPlyrAreaNo() && GetSisJoinFlg() != 0)   /* 849, 854 */
        {
            /* The player changed room: she comes out on the far side, at a
             * position stored relative to the new room's origin. */
            dp = MapDoorGetDatListPtr(
                     door_id ^ (MapDoorRoomNo == GetPlyrAreaNo()));     /* 875 */
            if (dp == (MLOAD_DOOR_DAT *)0)
            {
                return -2;                                              /* 877 */
            }

            lp = MapLoadGetHeader();                                    /* 880 */
            _SetVector(rpos, lp->pos[0], lp->pos[1], lp->pos[2], 1.0f); /* 881 */
            sceVu0AddVector(rpos, dp->sister_pos, rpos);                /* 882 */

            SetSisterPos(rpos);                                         /* 886 */
            SetSisterFloorPL();                                         /* 887 */
            SetSisterRotY(MapDoorCalcRotY(dp->sister_rot, door->Rot[1])); /* 888 */
            ChangeForceTraceMode();                                     /* 890 */
        }
        else if (MapDoorRoomNo == GetPlyrAreaNo() && GetSisJoinFlg() != 0) /* 857, 858 */
        {
            /* The player backed out: she ends up where he would have, in the
             * door's own frame, turned to face back the way they came. */
            dp = MapDoorGetDatListPtr(
                     door_id ^ (MapDoorRoomNo != GetPlyrAreaNo()));     /* 859 */
            if (dp == (MLOAD_DOOR_DAT *)0)
            {
                return -2;                                              /* 861 */
            }

            MapDoorSetMatrix(mat, door->Pos, door->Rot);                /* 862 */
            sceVu0ApplyMatrix(vw, mat, dp->player_pos);                 /* 864 */

            SetSisterPos(vw);                                           /* 865 */
            SetSisterFloorPL();                                         /* 867 */

            fw = MapDoorCalcRotY(dp->player_rot, door->Rot[1]) + MAPDOOR_PI;
            RotLimitChk(&fw);
            SetSisterRotY(fw);
            ChangeForceTraceMode();
        }
    }

    MapLoadSetDrawFlg(2, 2);                                            /* 897 */
    MapDoorCtlID  = -1;                                                 /* 899 */
    MapDoorRoomNo = -1;                                                 /* 903 */

    if (snd_utilAutoRelease(SndBankPlay(door_bank_id, 1, 1, 1, 0x3200,
                                        0x1000, 0, (SND_3D_SET *)0),
                            door_bank_id) == AUTO_BD_ERR_OK)            /* 906, 911 */
    {
        door_bank_id = -1;
    }

    return 0;
}                                                                       /* 912 */

