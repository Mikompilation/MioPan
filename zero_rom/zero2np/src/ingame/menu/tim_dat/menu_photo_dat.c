// thumbnail cells down the left, the enlarged picture on the right, the
// information window under it, and the two pop-up menus (the per-photo
// sub-menu and the sort menu).  Several groups are indexed by one of the
// six .rodata lookup tables in menu_photo.c rather than walked in order --
// bg_tbl / sel_tbl / protect_tbl / number_tbl are all sixteen entries long
// and correspond to the sixteen album slots.
//
// Four paks feed it.  The three menu-wide ones (MENU_BG, plus the two shared
// picture sheets) are already resident when the page opens; everything else
// comes out of MENU_PHOTO_PK2 + GetLanguage(), which is what
