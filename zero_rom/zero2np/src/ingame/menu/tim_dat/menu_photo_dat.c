// between groups.
//
// Twenty-five entries are never drawn: 19..42 (an inner frame of ticks and
// hairlines around the big picture) and 187.  They are kept because the ROM
// has them.
//
// Read straight out of the ROM's .data and diffed against it byte-for-byte.
//
