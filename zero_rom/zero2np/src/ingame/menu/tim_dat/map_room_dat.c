// The room registry behind the in-game map screen.  Four tables, each
// terminated by an all -1 record rather than carrying a count:
//
//   map_info_dat[]  - map_label -> texture id for the map page itself.
//   room_info_dat[] - the master room list.  GetMapLabelToRoomLabel()
//                     scans it for a room_label and hands back the map the
//                     room sits on; the snap/room texture ids drive the
//                     photographed-room and room-name plates.
//   house_info_dat[]- rooms that stand in for a whole building.  Entering
//                     any room in [start_room_label, end_room_label] also
//                     marks room_label as visited (HouseInCheck()).
//   area_map_tbl[]  - (area_label, floor_label) -> map_label, resolved by
//                     GetMapLabelFromAreaLabel() (menu_map.c).  floor_label
//                     only disambiguates for area_label >= 13.
//
