// The photo album's sprite bank.  434 SPRT_DAT records covering every page of
// the album -- the two-album edit page, the photo viewer, the info window, the
// confirm window and the memory-card save screen -- plus the three
// language-dependent x tables the save screen places its album name and its
// two arrows with.
//
// The object has no code: album_dat.o's 0xd4 of .text is the four fixed_array.h
// helpers every TU in this folder emits, and nothing else.  Everything here is
// .data / .rodata.
//
// How the bank is indexed:
//
//   * Runs of ten are digit sets.  [39..108] is seven of them, one per album
//     type, selected by album_disp.c's num_tex_tbl[]; [138..147] is the
//     thumbnail slot numbers; [149..158] the photo counts.
//   * Anything "per album type" is a run of 7 (or 7 pairs) indexed by
//     ALBUM_INFO::album_type.  Types 5 and 6 are the two that have no save
//     screen presence, which is why the tails of those runs are -1 in
//     album_disp.c's tables rather than sprite records here.
//   * Groups sharing a tex0 and differing only in flip are one image mirrored.
//
// The tex0 values are packed GS register payloads baked by the asset pipeline
// and are preserved verbatim from the build.
//
// Extracted verbatim from the Feb 6 2004 prototype (SLES_523.84), data 2d4788
// and rdata 3a0230 (album_dat.o, whose only content this is).

